"""Generate the pixel-scroll ornament masks used by effects/pixel-ornament.
Usage: python art/pixel_ornament.py   (pure stdlib)  ->  effects/pixel-ornament/ornament.css
Grid is 40x68 cells (aspect 0.59, matches a 640x1080 column). Two masks are written as CSS variables:
  --orn-full  every ornament cell opaque (shape of the ornament)
  --orn-var   per-cell random alpha (some cells see-through, so the photo shows between white cells)
"""
import math, random, urllib.parse

W, H = 40, 68
cells = set()

def put(x, y, t=1):
    for dx in range(t):
        for dy in range(t):
            cx, cy = int(x) + dx, int(y) + dy
            if 0 <= cx < W and 0 <= cy < H:
                cells.add((cx, cy))

def spiral(cx, cy, r0, r1, turns, a0, d, t=2):
    pts = []
    n = 600
    for i in range(n + 1):
        u = i / n
        r = r0 + (r1 - r0) * u
        a = a0 + d * turns * 2 * math.pi * u
        x, y = cx + r * math.cos(a), cy + r * math.sin(a)
        put(x, y, t)
        pts.append((x, y))
    return pts

def bez(p0, p1, p2, p3, t=2):
    for i in range(401):
        u = i / 400
        x = (1-u)**3*p0[0] + 3*(1-u)**2*u*p1[0] + 3*(1-u)*u**2*p2[0] + u**3*p3[0]
        y = (1-u)**3*p0[1] + 3*(1-u)**2*u*p1[1] + 3*(1-u)*u**2*p2[1] + u**3*p3[1]
        put(x, y, t)

# chain of five scrolls, alternating left / right, joined by S curves
S = [spiral(11, 10, 1.2, 7.2, 1.35, math.pi * .2, 1),
     spiral(29, 22, 1.2, 7.2, 1.35, math.pi * .8, -1),
     spiral(11, 35, 1.2, 7.2, 1.35, math.pi * .2, 1),
     spiral(29, 47, 1.2, 7.2, 1.35, math.pi * .8, -1),
     spiral(12, 59, 1.2, 6.2, 1.35, math.pi * .2, 1)]
for a, b in zip(S, S[1:]):
    p0, p3 = a[-1], b[-1]
    bez(p0, (p0[0], p0[1] + 9), (p3[0], p3[1] - 9), p3)
# a few loose leaves / blobs on the sides
for (x, y, s) in [(3, 22, 3), (33, 8, 3), (4, 48, 3), (34, 36, 3), (20, 3, 3), (22, 64, 3)]:
    put(x, y, s)

rnd = random.Random(7)

def svg(alpha):
    rects = ''.join(
        f"<rect x='{x}' y='{y}' width='1' height='1' fill='white'" + (f" fill-opacity='{alpha(x, y):.2f}'" if alpha else '') + "/>"
        for (x, y) in sorted(cells, key=lambda c: (c[1], c[0])))
    s = f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {W} {H}' shape-rendering='crispEdges' preserveAspectRatio='none'>{rects}</svg>"
    return 'url("data:image/svg+xml;utf8,' + urllib.parse.quote(s, safe="/:=' <>") .replace('"', "'") + '")'

full = svg(None)
vals = {}
def a_var(x, y):
    return vals.setdefault((x, y), rnd.choice([1] * 11 + [.85, .6, .3, 0]))
var = svg(a_var)

css = f"""/* GENERATED by art/pixel_ornament.py — 不要手改。 */
:root{{--orn-full:{full};--orn-var:{var};}}
/* .px-orn:一个和照片同位置同大小的盒子,里面放同一张 <img>。
   盒子被花纹遮罩裁成像素旋涡;旋涡里是像素化+提亮的照片,再盖一层逐格半透明的白,
   所以大部分格子是白的,少数格子透出照片的颜色。需要页面里有 id="pixelate" 的 SVG 滤镜(见 demo)。 */
.px-orn{{position:absolute;overflow:hidden;-webkit-mask:var(--orn-full) center/100% 100% no-repeat;mask:var(--orn-full) center/100% 100% no-repeat}}
.px-orn>img{{position:absolute;inset:0;width:100%;height:100%;object-fit:cover;filter:url(#pixelate) brightness(1.35) saturate(.75)}}
.px-orn::after{{content:"";position:absolute;inset:0;background:#fff;opacity:var(--orn-white,.92);-webkit-mask:var(--orn-var) center/100% 100% no-repeat;mask:var(--orn-var) center/100% 100% no-repeat}}
.px-orn.flip{{transform:scaleY(-1)}}
/* .px-lace:同一个花纹用点阵填充,做边缘蕾丝。--lace 点色 */
.px-lace{{position:absolute;background:radial-gradient(circle,var(--lace,#8fa6e0) 0 1.6px,transparent 2px) 0 0/7px 7px;-webkit-mask:var(--orn-full) center/100% 100% no-repeat;mask:var(--orn-full) center/100% 100% no-repeat}}
"""
open('effects/pixel-ornament/ornament.css', 'w').write(css)
print('cells', len(cells), 'css bytes', len(css))
