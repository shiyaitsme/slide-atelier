// Builds fonts.css (base64 woff2) from @fontsource packages. Only the CJK slices that contain glyphs used in index.html are embedded.
// Usage: FONTSRC=/path/to/node_modules/@fontsource node build-fonts.js   (npm i @fontsource/cormorant-garamond @fontsource/dm-sans @fontsource/space-mono @fontsource/silkscreen @fontsource/noto-serif-sc)
const fs = require('fs'), path = require('path');
const root = process.env.FONTSRC || path.join(__dirname, 'node_modules/@fontsource');
const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
const need = new Set(); for (const ch of html) { const c = ch.codePointAt(0); if (c > 127) need.add(c); }
const b64 = f => fs.readFileSync(f).toString('base64');
let css = '/* generated by build-fonts.js */\n';
const face = (family, style, weight, file, range) =>
  `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${b64(file)}) format('woff2');${range ? 'unicode-range:' + range + ';' : ''}}\n`;
const simple = (pkg, family, list) => list.forEach(([w, s]) => { css += face(family, s, w, `${root}/${pkg}/files/${pkg}-latin-${w}-${s}.woff2`); });
simple('cormorant-garamond', 'Cormorant Garamond', [[500, 'normal'], [500, 'italic'], [700, 'normal']]);
simple('dm-sans', 'DM Sans', [[400, 'normal'], [500, 'normal'], [700, 'normal']]);
simple('space-mono', 'Space Mono', [[400, 'normal'], [700, 'normal']]);
simple('silkscreen', 'Silkscreen', [[400, 'normal']]);
let used = 0;
for (const w of [400, 700]) {
  const src = fs.readFileSync(`${root}/noto-serif-sc/${w}.css`, 'utf8');
  for (const m of src.matchAll(/@font-face\s*{[^}]*?url\(\.\/files\/([^)]+?\.woff2)\)[^}]*?unicode-range:\s*([^;]+);/g)) {
    const ranges = m[2].split(',').map(r => r.trim().replace('U+', '').split('-').map(h => parseInt(h, 16)));
    if ([...need].some(c => ranges.some(([a, b]) => c >= a && c <= (b ?? a)))) { css += face('Noto Serif SC', 'normal', w, `${root}/noto-serif-sc/files/${m[1]}`, m[2]); used++; }
  }
}
fs.writeFileSync(path.join(__dirname, 'fonts.css'), css);
console.log('glyphs needed:', need.size, 'CJK slices embedded:', used, 'size KB:', Math.round(css.length / 1024));
